def format_context(results: list[RetrievedChunk]) -> str:
    lines = [f'<doc id="{r.chunk.id}">{r.chunk.text}</doc>' for r in results]
    return "<knowledge>\n" + "\n".join(lines) + "\n</knowledge>"


def build_user_turn(question: str, results: list[RetrievedChunk]) -> str:
    return f"{format_context(results)}\n\n<customer_question>\n{question}\n</customer_question>"


