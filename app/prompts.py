def _rules_block(rules: dict) -> str:
    must = "\n".join(f"- {r}" for r in rules["must_do"])
    never = "\n".join(f"- {r}" for r in rules["must_not_do"])
    esc = "\n".join(f"- {r}" for r in rules["escalation"])
    return f"สิ่งที่ต้องทำ:\n{must}\n\nสิ่งที่ห้ามทำ:\n{never}\n\nกรณีที่ต้องส่งต่อพนักงาน:\n{esc}"


